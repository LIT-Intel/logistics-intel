/** Case-insensitive substring lookup over the major-port table. */
export function portCoords(portName: string): [number, number] | null {
  if (!portName) return null;
  const q = portName.toLowerCase();
  for (const p of PORTS) {
    for (const a of p.aliases) {
      if (q.includes(a) || a.includes(q)) return p.coords;
    }
  }
  return null;
}

/** Origin of a lane: named port first, else the origin-country centroid. */
export function originCoords(oPort: string, oc: string): [number, number] | null {
  return portCoords(oPort) ?? COUNTRY_CENTROIDS[oc] ?? null;
}
